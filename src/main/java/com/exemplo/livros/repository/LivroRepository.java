package com.exemplo.livros.repository;

import com.exemplo.livros.model.Livro;

import java.sql.*;
import java.util.ArrayList;
import java.util.List;

public class LivroRepository {

    private final Connection connection;

    public LivroRepository() throws SQLException {
        connection = DriverManager.getConnection(
                "jdbc:h2:./data/livrosdb",
                "sa",
                ""
        );

        criarTabela();
    }

    private void criarTabela() throws SQLException {
        String sql = """
                CREATE TABLE IF NOT EXISTS livros (
                    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                    titulo VARCHAR(255) NOT NULL,
                    autor VARCHAR(255) NOT NULL,
                    ano INT NOT NULL
                )
                """;

        try (Statement statement = connection.createStatement()) {
            statement.execute(sql);
        }
    }

    public Livro salvar(Livro livro) throws SQLException {

        String sql = """
                INSERT INTO livros (titulo, autor, ano)
                VALUES (?, ?, ?)
                """;

        try (PreparedStatement statement =
                     connection.prepareStatement(sql, Statement.RETURN_GENERATED_KEYS)) {

            statement.setString(1, livro.getTitulo());
            statement.setString(2, livro.getAutor());
            statement.setInt(3, livro.getAno());

            statement.executeUpdate();

            try (ResultSet result = statement.getGeneratedKeys()) {
                if (result.next()) {
                    livro.setId(result.getLong(1));
                }
            }
        }

        return livro;
    }

    public List<Livro> listar() throws SQLException {

        List<Livro> livros = new ArrayList<>();

        String sql = """
                SELECT id, titulo, autor, ano
                FROM livros
                ORDER BY id
                """;

        try (PreparedStatement statement = connection.prepareStatement(sql);
             ResultSet result = statement.executeQuery()) {

            while (result.next()) {
                Livro livro = new Livro(
                        result.getLong("id"),
                        result.getString("titulo"),
                        result.getString("autor"),
                        result.getInt("ano")
                );

                livros.add(livro);
            }
        }

        return livros;
    }
}
